"""Generate the csh scripts each step runs (+ the /bin/sh launchers used over ssh).

The scripts ARE the flow: Airflow only launches them and reads their status files, so every
step can be re-run by hand outside Airflow with exactly the same result:
    ssh <pd host>;  csh -f <run>/scripts/30_compile.csh
"""
from __future__ import annotations

import filecmp
import shutil
import time
from pathlib import Path

from .config import FC_STEPS, MARKERS_AFTER, STEPS

SCRIPT_NAMES = {s: f"{10 * (i + 1)}_{s}.csh" for i, s in enumerate(STEPS)}


def script_path(ctx: dict, step: str) -> Path:
    return Path(ctx["run_dir"]) / "scripts" / SCRIPT_NAMES[step]


def launcher_path(ctx: dict, step: str) -> Path:
    return Path(ctx["run_dir"]) / "scripts" / f"launch_{step}.sh"


def tool_log(ctx: dict, step: str) -> Path:
    """The log the tool itself writes (streamed into the Airflow task log)."""
    if step == "build":
        return Path(ctx["run_dir"]) / "logs" / "build.console.log"
    return Path(ctx["module_dir"]) / "rm_fc" / "logs" / f"{step}.log"


def _hdr(ctx: dict, what: str) -> str:
    return (f"# Generated by pdflow {time.strftime('%Y-%m-%d %H:%M:%S')} -- run {ctx['run_tag']} "
            f"({ctx['module']}, {ctx['build_config']}, Clk_period {ctx['clk_str']} ns, "
            f"max_cores {ctx['max_cores']})\n# {what}\n")


def render_env_fc(ctx: dict, fixed: dict) -> str:
    lines = [_hdr(ctx, "Environment for the Fusion Compiler steps (sourced by 20..70_*.csh)."),
             "unsetenv DISPLAY            # report_qor.tcl calls gui_start when DISPLAY is set",
             f"source {fixed['module_init']}",
             "module purge                # a manual re-run must not inherit another fc (source_env loads X-2025.06)"]
    lines += [f"module use {d}" for d in fixed["module_use"]]
    lines += [f"module load {fixed['fc_module']}",
              f"setenv MIPS_HOME   {fixed['mips_home']}",
              f"setenv TECH_DIR    {ctx['tech_dir']}",
              f"setenv DESIGN_NAME {ctx['design_name']}",
              f"setenv SYN_CONFIG  {ctx['build_config']}"]
    lines += [f"setenv {k} {v}" for k, v in fixed["license_env"].items()]
    return "\n".join(lines) + "\n"


def render_env_build(ctx: dict, fixed: dict) -> str:
    run = ctx["run_dir"]
    lines = [_hdr(ctx, "Environment for the RTL build (sourced by 10_build.csh)."),
             "unsetenv DISPLAY",
             "# source_env.csh appends to these; under a clean env they must exist first",
             'if ( ! $?LD_LIBRARY_PATH ) setenv LD_LIBRARY_PATH ""',
             'if ( ! $?PERL5LIB ) setenv PERL5LIB ""']
    lines += [f"setenv {k} {v}" for k, v in fixed["build_env_extra"].items()]
    lines += [f"source {fixed['module_init']}",
              f"setenv MIPS_HOME {fixed['mips_home']}",
              f"source {fixed['raven_env']} {fixed['mips_home']}/raven >& {run}/logs/build.source_env.log"]
    return "\n".join(lines) + "\n"


_PROLOGUE = """#!/bin/csh -f
{hdr}# Re-run by hand on a pd host:  csh -f {self_path}
set RUN  = "{run}"
set STEP = "{step}"
set ST   = "$RUN/status"
set TS   = `date +%Y%m%d-%H%M%S`
set rc   = 99
set H    = `hostname`
rm -f "$ST/$STEP.rc" "$ST/$STEP.end"
# status files are written to a temp name + mv (atomic on NFS): the watcher never reads half a file.
# Under the pdflow launcher the /bin/sh session leader writes the pid; a manual run writes its own.
if ( ! $?PDFLOW_LAUNCHED ) then
    echo "$H $$" >! "$ST/.$STEP.pid.$$"
    mv -f "$ST/.$STEP.pid.$$" "$ST/$STEP.pid"
endif
date +%s >! "$ST/.$STEP.start.$$"
mv -f "$ST/.$STEP.start.$$" "$ST/$STEP.start"
echo "pdflow: $STEP starting on $H pid $$ at `date`"
"""

_EPILOGUE = """
done:
date +%s >! "$ST/.$STEP.end.$$"
mv -f "$ST/.$STEP.end.$$" "$ST/$STEP.end"
echo $rc >! "$ST/.$STEP.rc.$$"
mv -f "$ST/.$STEP.rc.$$" "$ST/$STEP.rc"
echo "pdflow: $STEP finished rc=$rc at `date`"
exit $rc
"""


def render_build(ctx: dict, fixed: dict) -> str:
    cfg = ctx["build_config"]
    fargs = " ".join(f"-f {f}" for f in fixed["build_extra_f"])
    cmd = (f'"$bpy" {fixed["build_project"]} -t {ctx["top_file"]} --configName {cfg} '
           f'--workDirectory {cfg} -bt {fixed["build_target"]} -tech {fixed["build_tech"]} {fargs}')
    body = f"""
foreach f ( "{fixed['module_init']}" "{fixed['raven_env']}" "$RUN/scripts/env_build.csh" )
    if ( ! -r "$f" ) then
        echo "pdflow: ERROR cannot read $f"
        set rc = 97
        goto done
    endif
end
source "$RUN/scripts/env_build.csh"
if ( ! $?MIPSARCHROOT ) then
    echo "pdflow: ERROR source_env.csh did not set up the build environment (see $RUN/logs/build.source_env.log)"
    set rc = 93
    goto done
endif
set bpy = "{fixed['build_py']}"
if ( ! -x "$bpy" ) then
    echo "pdflow: ERROR build.py not executable: $bpy"
    set rc = 94
    goto done
endif
if ( ! -d "{ctx['rc_dir']}/vbuild" ) then
    echo "pdflow: ERROR missing {ctx['rc_dir']}/vbuild"
    set rc = 95
    goto done
endif
cd "{ctx['rc_dir']}/vbuild"
# build.py writes rdl_generate.log into the CWD (not into -w): keep the previous one
if ( -e rdl_generate.log ) mv -f rdl_generate.log rdl_generate.log.$TS
echo "pdflow: {cmd}"
{cmd} < /dev/null >& "$RUN/logs/build.console.log"
set rc = $status
"""
    return _PROLOGUE.format(hdr=_hdr(ctx, "Step build: pyBuildSim RTL filelist generation"),
                            self_path=script_path(ctx, "build"), run=ctx["run_dir"], step="build") \
        + body + _EPILOGUE


def render_fc_step(ctx: dict, fixed: dict, step: str) -> str:
    tmp = f"{ctx['module_dir']}/rm_fc/tmp"
    markers = " ".join(MARKERS_AFTER[step])
    make_eq = (f"make -f ../../scripts_block/rm_setup/Makefile {step} TECH_DIR={ctx['tech_dir']} "
               f"DESIGN_NAME={ctx['design_name']} SYN_CONFIG={ctx['build_config']}")
    place_opt = ("\n# UNIFIED_FLOW=true: compile already saved the place_opt label; the Makefile's place_opt "
                 "target only writes its marker\nif ( $rc == 0 && -e compile ) then\n    date >! place_opt\nendif\n"
                 if step == "compile" else "")
    fc_prefix = fixed.get("fc_shell_prefix", "")
    body = f"""
foreach f ( "{fixed['module_init']}" "$RUN/scripts/env_fc.csh" )
    if ( ! -r "$f" ) then
        echo "pdflow: ERROR cannot read $f"
        set rc = 97
        goto done
    endif
end
source "$RUN/scripts/env_fc.csh"
set fcbin = `which fc_shell`
if ( ! -x "$fcbin" ) then
    echo "pdflow: ERROR fc_shell not on PATH after 'module load {fixed['fc_module']}'"
    set rc = 96
    goto done
endif
if ( "{fc_prefix}" != "" && "$fcbin" !~ {fc_prefix}* ) then
    echo "pdflow: ERROR wrong fc_shell $fcbin (expected {fc_prefix}...)"
    set rc = 96
    goto done
endif
if ( ! -d "{tmp}" ) then
    echo "pdflow: ERROR missing {tmp}"
    set rc = 95
    goto done
endif
cd "{tmp}"
# Equivalent Makefile call (NOT used: its `| tee` hides fc_shell's exit status and make would
# silently re-run prerequisites -- re-running init_design deletes the .nlib):
#   {make_eq}
# (block form on purpose: a one-line csh `if (...) cmd >! file` leaves the file EMPTY)
if ( ! -e setup ) then
    date >! setup
endif
# A stale marker must never make a failed re-run look finished: drop this step's + later ones
rm -f {markers}
mkdir -p ../logs
if ( -e ../logs/{step}.log ) mv -f ../logs/{step}.log ../logs/{step}.log.$TS
if ( -d ../rpts/{step} ) mv -f ../rpts/{step} ../rpts/{step}.$TS
echo "pdflow: $fcbin -f ../../scripts_block/rm_fc_scripts/{step}.tcl  (log {ctx['module_dir']}/rm_fc/logs/{step}.log)"
fc_shell -f ../../scripts_block/rm_fc_scripts/{step}.tcl < /dev/null >& ../logs/{step}.log
set rc = $status
{place_opt}"""
    return _PROLOGUE.format(hdr=_hdr(ctx, f"Step {step}: Fusion Compiler RM {step}.tcl"),
                            self_path=script_path(ctx, step), run=ctx["run_dir"], step=step) \
        + body + _EPILOGUE


def render_launcher(ctx: dict, fixed: dict, step: str) -> str:
    run = ctx["run_dir"]
    return f"""#!/bin/sh
# Generated by pdflow: start step {step} DETACHED on this host (own session = own process group).
# Airflow runs:  ssh <pd host> /bin/sh {launcher_path(ctx, step)}
# The job then survives ssh/Airflow restarts; it reports through {run}/status/{step}.{{pid,rc,start,end}}.
# The session leader is a tiny /bin/sh: it records its pid (= session id = process group), runs
# the csh step script, and writes the exit code itself if csh died without writing one.
cd "{run}" || exit 90
umask 022
setsid env -i HOME="$HOME" USER="$USER" LOGNAME="$USER" SHELL=/bin/tcsh TERM=dumb LANG=C \\
    PATH={fixed['clean_env_path']} PDFLOW_LAUNCHED=1 /bin/sh -c '
  st="$1/status"; step="$2"; script="$3"
  echo "$(hostname) $$" > "$st/.$step.pid.$$" && mv -f "$st/.$step.pid.$$" "$st/$step.pid"
  /bin/csh -f "$script"; rc=$?
  if [ ! -s "$st/$step.rc" ]; then
    date +%s > "$st/.$step.end.$$"; mv -f "$st/.$step.end.$$" "$st/$step.end"
    echo "$rc" > "$st/.$step.rc.$$"; mv -f "$st/.$step.rc.$$" "$st/$step.rc"
  fi' pdflow-{step} "{run}" "{step}" "{script_path(ctx, step)}" \\
    </dev/null >"{run}/logs/{step}.wrapper.log" 2>&1 &
echo "launched {step} pid $! on $(hostname)"
"""


def _write(path: Path, text: str, archive: Path, mode=0o755) -> None:
    if path.exists():
        tmp = path.with_name(path.name + ".new")
        tmp.write_text(text)
        if filecmp.cmp(tmp, path, shallow=False):
            tmp.unlink()
            return
        archive.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, archive / path.name)
        tmp.replace(path)
    else:
        path.write_text(text)
    path.chmod(mode)


def write_all(ctx: dict, fixed: dict) -> dict:
    """(Re)write every script. Changed scripts keep their previous version in scripts/.prev-<ts>/."""
    sdir = Path(ctx["run_dir"]) / "scripts"
    sdir.mkdir(parents=True, exist_ok=True)
    archive = sdir / f".prev-{time.strftime('%Y%m%d-%H%M%S')}"
    out = {"env_fc": sdir / "env_fc.csh", "env_build": sdir / "env_build.csh"}
    _write(out["env_fc"], render_env_fc(ctx, fixed), archive, 0o644)
    _write(out["env_build"], render_env_build(ctx, fixed), archive, 0o644)
    _write(script_path(ctx, "build"), render_build(ctx, fixed), archive)
    out["build"] = script_path(ctx, "build")
    for s in FC_STEPS:
        _write(script_path(ctx, s), render_fc_step(ctx, fixed, s), archive)
        out[s] = script_path(ctx, s)
    for s in STEPS:
        _write(launcher_path(ctx, s), render_launcher(ctx, fixed, s), archive)
    return {k: str(v) for k, v in out.items()}
